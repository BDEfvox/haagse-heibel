// Which OpenStreetMap building parts lie inside a hand-made landmark (src/voxel/specials*.js)? Those parts must not be
// drawn on top of the hand-made shape. Runs after build-world.mjs (npm run world) and writes src/voxel/special-parts.js.
import fs from 'node:fs';
import { SPECIALS } from '../src/voxel/specials.js';
import { SPECIALS2 } from '../src/voxel/specials2.js';

const T = 256, dir = new URL('../public/data/world/tiles/', import.meta.url);
const load = (tx, ty) => { try { return JSON.parse(fs.readFileSync(new URL(`${tx}_${ty}.json`, dir))); } catch { return null; } };
const ringOf = (e, at, tx, ty) => { const r = []; for (let i = at; i + 1 < e.length; i += 2) r.push([tx * T + e[i] / 10, ty * T + e[i + 1] / 10]); return r; };
const inRing = (x, y, r) => { let c = false; for (let i = 0, k = r.length - 1; i < r.length; k = i++) if ((r[i][1] > y) !== (r[k][1] > y) && x < ((r[k][0] - r[i][0]) * (y - r[i][1])) / (r[k][1] - r[i][1]) + r[i][0]) c = !c; return c; };
const area = (r) => { let a = 0; for (let i = 0, k = r.length - 1; i < r.length; k = i++) a += r[k][0] * r[i][1] - r[i][0] * r[k][1]; return Math.abs(a) / 2; };

const out = {}, report = [];
for (const s of [...SPECIALS, ...SPECIALS2]) {
  const tx0 = Math.floor(s.x / T), ty0 = Math.floor(s.y / T);
  let home = null;
  for (let tx = tx0 - 1; tx <= tx0 + 1 && !home; tx++) for (let ty = ty0 - 1; ty <= ty0 + 1 && !home; ty++) {
    const t = load(tx, ty);
    for (const e of (t && t.b) || []) {
      const r = ringOf(e, 3, tx, ty);
      let x0 = Infinity, x1 = -Infinity, y0 = Infinity, y1 = -Infinity;
      for (const [x, y] of r) { if (x < x0) x0 = x; if (x > x1) x1 = x; if (y < y0) y0 = y; if (y > y1) y1 = y; }
      if (Math.abs((x0 + x1) / 2 - s.x) < 12 && Math.abs((y0 + y1) / 2 - s.y) < 12 && area(r) >= (s.minArea || 0)) { home = { r, x0, x1, y0, y1 }; break; }
    }
  }
  if (!home) { report.push(`${s.id}: NO BUILDING MATCHES (check x, y, minArea)`); continue; }
  let n = 0;
  for (let tx = Math.floor(home.x0 / T) - 1; tx <= Math.floor(home.x1 / T) + 1; tx++) for (let ty = Math.floor(home.y0 / T) - 1; ty <= Math.floor(home.y1 / T) + 1; ty++) {
    const t = load(tx, ty);
    ((t && t.q) || []).forEach((e, qi) => {
      const r = ringOf(e, 6, tx, ty);
      let cx = 0, cy = 0, inN = 0;
      for (const [x, y] of r) { cx += x; cy += y; if (inRing(x, y, home.r)) inN++; }
      if (inRing(cx / r.length, cy / r.length, home.r) || inN * 2 > r.length) { (out[`${tx}_${ty}`] ||= []).push(qi); n++; }
    });
  }
  report.push(`${s.id}: ${n} part${n === 1 ? '' : 's'}`);
}
for (const k of Object.keys(out)) out[k] = [...new Set(out[k])].sort((a, b) => a - b);
const keys = Object.keys(out).sort();
fs.writeFileSync(new URL('../src/voxel/special-parts.js', import.meta.url),
  `// Generated by scripts/special-parts.mjs (npm run world): building parts hidden under a hand-made landmark, per tile.\nexport const SPECIAL_PARTS = {\n${keys.map((k) => `  '${k}': [${out[k].join(', ')}],`).join('\n')}\n};\n`);
console.log('[special-parts] ' + report.join('; '));
